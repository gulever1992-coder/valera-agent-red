# Схема-референс «Цех сортировки» v2 (карта D: 4 этажа в разрезе, «кукольный дом») для Flow — не графика игры.
# Мир: 1200 лог. px в ширину, полы этажей y=300/160/20/-120; картинка 1376x768 покрывает y от -310 до 360 (масштаб 1376/1200).
import os
from PIL import Image, ImageDraw
K = 1376 / 1200; Y0 = 360 - 768 / K; W, H = 1376, 768
FL = [300, 160, 20, -120]; SLAB = 26; CEIL = 114
im = Image.new('RGB', (W, H), (255, 0, 255)); d = ImageDraw.Draw(im)
P = lambda x, y: (x * K, (y - Y0) * K)
def box(x0, y0, x1, y1, fill=None, w=3): d.rectangle([P(x0, y0), P(x1, y1)], fill=fill, outline='black', width=w)
def ladder(x, y0, y1):
    for dx in (-9, 9): d.line([P(x + dx, y0), P(x + dx, y1 - 6)], fill='black', width=3)
    for y in range(int(y1), int(y0), 10): d.line([P(x - 9, y), P(x + 9, y)], fill='black', width=2)
box(0, FL[3] - CEIL - 18, 1200, 360, (236, 236, 236))                       # коробка здания
for f in FL: box(22, f - CEIL, 1178, f, (250, 250, 250), 2)                 # комнаты
for f in FL: box(0, f, 1200, f + SLAB, (120, 120, 120), 2)                  # перекрытия
box(0, 300, 1200, 360, (90, 90, 90))                                        # фундамент
box(0, FL[3] - CEIL - 18, 22, 300, (150, 90, 70)); box(1178, FL[3] - CEIL - 18, 1200, 300, (150, 90, 70))   # кирпичные стены в разрезе
box(0, FL[3] - CEIL - 28, 1200, FL[3] - CEIL - 18, (60, 60, 60))            # парапет крыши
for x in (300, 700, 980): d.line([P(x, FL[3] - CEIL - 28), P(x, Y0)], fill='black', width=3)   # антенны/трубы на крыше
# лестницы и люки в перекрытиях
for x, f in ((860, 0), (100, 1), (1090, 2)):
    box(x - 18, FL[f + 1], x + 18, FL[f + 1] + SLAB, (250, 250, 250), 1); ladder(x, FL[f], FL[f + 1] - 4)
# 1 этаж: вход слева, ящики, гермодверь справа с окошком и табло
box(34, 204, 84, 300, (180, 180, 180)); box(170, 262, 226, 300, (200, 170, 120)); box(380, 250, 470, 300, (200, 170, 120)); box(560, 268, 610, 300, (200, 170, 120))
box(1040, 196, 1124, 300, (140, 150, 150), 4); box(1058, 222, 1106, 254, (200, 230, 230), 3); box(1036, 172, 1128, 190, (40, 40, 40))
# 2 этаж: шкафчики, стеллажи, ящики
for x in (486, 508, 530): box(x, 76, x + 22, 160, (150, 170, 190), 2)
box(650, 128, 710, 160, (200, 170, 120)); box(250, 70, 380, 160, None, 2); box(950, 70, 1100, 160, None, 2)
# 3 этаж: стол с мониторами, стойки, пульт
box(250, -14, 340, 20, (170, 150, 120)); box(262, -44, 292, -16, (60, 80, 90)); box(300, -44, 330, -16, (60, 80, 90))
for x in (420, 450, 480): box(x, -66, x + 28, 20, (70, 80, 90), 2)
box(618, -58, 672, -20, (90, 100, 110), 3); d.ellipse([P(637, -47), P(653, -31)], fill=(220, 40, 40))
box(770, -50, 880, 20, None, 2)
# 4 этаж: дверь на крышу со щитком, вентиляция
box(52, -216, 104, -120, (180, 180, 180)); box(118, -180, 134, -156, (100, 100, 100), 2); box(250, -160, 330, -120, (200, 170, 120)); box(380, -150, 420, -120, (200, 170, 120))
d.ellipse([P(760, -222), P(840, -142)], outline='black', width=3); box(900, -232, 1178, -214, (170, 170, 170), 2)
im.save(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'p7v4', 'towerref.png')); print('ok', Y0)
